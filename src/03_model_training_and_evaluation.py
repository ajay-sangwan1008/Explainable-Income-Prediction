#load data

X_train = pd.read_csv(f"{PROCESSED_DATA_PATH}/X_train.csv")
X_test = pd.read_csv(f"{PROCESSED_DATA_PATH}/X_test.csv")

y_train = pd.read_csv(f"{PROCESSED_DATA_PATH}/y_train.csv").squeeze()

y_test = pd.read_csv(f"{PROCESSED_DATA_PATH}/y_test.csv").squeeze()

print(X_train.shape)
