# Group-wise Fairness Metrics

def fairness_metrics(y_true, y_pred, groups):

    data = pd.DataFrame({
        "Actual": y_true,
        "Predicted": y_pred,
        "Group": groups
    })

    results = []

    for group in data["Group"].unique():

        subset = data[data["Group"] == group]

        actual = subset["Actual"].to_numpy()
        predicted = subset["Predicted"].to_numpy()

        tp = np.sum((actual == 1) & (predicted == 1))
        tn = np.sum((actual == 0) & (predicted == 0))
        fp = np.sum((actual == 0) & (predicted == 1))
        fn = np.sum((actual == 1) & (predicted == 0))

        selection_rate = np.mean(predicted == 1)

        tpr = tp / (tp + fn) if (tp + fn) > 0 else np.nan
        fpr = fp / (fp + tn) if (fp + tn) > 0 else np.nan

        results.append({
            "Group": group,
            "Count": len(subset),
            "Actual_Positive_Rate": np.mean(actual == 1),
            "Predicted_Positive_Rate": selection_rate,
            "TPR": tpr,
            "FPR": fpr
        })

    return pd.DataFrame(results)

