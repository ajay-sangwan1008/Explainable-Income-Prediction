# Fairness Disparity Summary

def disparity_summary(fairness_df):

    selection_rates = fairness_df["Predicted_Positive_Rate"]
    tpr_values = fairness_df["TPR"]
    fpr_values = fairness_df["FPR"]

    return pd.DataFrame({
        "Metric": [
            "Selection Rate Difference",
            "TPR Difference",
            "FPR Difference"
        ],
        "Maximum": [
            selection_rates.max() - selection_rates.min(),
            tpr_values.max() - tpr_values.min(),
            fpr_values.max() - fpr_values.min()
        ]
    })


