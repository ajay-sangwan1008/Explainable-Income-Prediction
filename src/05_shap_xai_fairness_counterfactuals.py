# Counterfactual Search

counterfactuals = []

for feature in actionable_features:

    original_value = sample[feature]

    for value in candidate_values[feature]:

        if value == original_value:
            continue

        candidate = sample.copy()
        candidate[feature] = value

        candidate_df = pd.DataFrame(
            [candidate],
            columns=X_test.columns
        )

        probability = xgb_pipeline.predict_proba(
            candidate_df
        )[0, 1]

        if probability >= 0.5:

            counterfactuals.append({
                "Feature": feature,
                "Original": original_value,
                "Changed_to": value,
                "Probability": probability
            })

            # first crossing value for this feature
            break


counterfactual_df = pd.DataFrame(counterfactuals)

if counterfactual_df.empty:

    print("No single-feature counterfactual found.")

