# ==========================================================
# Section 16 : Hidden Missing Values
# ==========================================================

hidden_missing = {}

for column in df.columns:

    question_mark = (df[column] == "?").sum()

    question_mark_space = (df[column] == " ?").sum()

    total = question_mark + question_mark_space

    if total > 0:
        hidden_missing[column] = total

hidden_missing

#duplicate values

duplicates = df.duplicated().sum()

