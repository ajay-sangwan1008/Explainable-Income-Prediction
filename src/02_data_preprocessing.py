#preprocessing dataset


import warnings
warnings.filterwarnings("ignore")
import numpy as np
import pandas as pd
import joblib
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import (
    OneHotEncoder,
    StandardScaler
)


RAW_DATA_PATH = f"{PROJECT_PATH}/data/raw"

PROCESSED_DATA_PATH = f"{PROJECT_PATH}/data/processed"

MODEL_PATH = f"{PROJECT_PATH}/models"

RESULT_PATH = f"{PROJECT_PATH}/results"

FIGURE_PATH = f"{PROJECT_PATH}/figures"

REPORT_PATH = f"{PROJECT_PATH}/reports"

df=pd.read_csv(f"{RAW_DATA_PATH}/adult.csv")

#to convert the hidden values
df.replace(" ?",np.nan, inplace=True)
df.replace("?",np.nan, inplace=True)

df.isnull().sum()

#remove duplicates
print(f"Shape before removing duplicates : {df.shape}")
df = df.drop_duplicates().reset_index(drop=True)
print(f"Shape after removing duplicates : {df.shape}")

#saving clean dataset
df.to_csv(
    f"{PROCESSED_DATA_PATH}/adult_cleaned.csv",
    index=False
)

print("Cleaned dataset saved successfully.")

#separating features and target
X = df.drop(columns=["income"])

y = df["income"]

print(f"Feature Matrix Shape : {X.shape}")
print(f"Target Vector Shape  : {y.shape}")

#train test splitting
from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training Set :", X_train.shape)
print("Testing Set  :", X_test.shape)

#saving train and test splits
X_train.to_csv(f"{PROCESSED_DATA_PATH}/X_train.csv", index=False)
X_test.to_csv(f"{PROCESSED_DATA_PATH}/X_test.csv", index=False)
y_train.to_csv(f"{PROCESSED_DATA_PATH}/y_train.csv", index=False)
y_test.to_csv(f"{PROCESSED_DATA_PATH}/y_test.csv", index=False)
print("Train-test datasets saved successfully.")

#identifying feature types
numerical_features = X_train.select_dtypes(
    include=["int64", "float64"]
).columns.tolist()

categorical_features = X_train.select_dtypes(
    include=["object"]
).columns.tolist()

print("Numerical Features")
print(numerical_features)

print("\nCategorical Features")
print(categorical_features)

#numerical pipeline
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

numeric_pipeline = Pipeline(
    steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler())
    ]
)

numeric_pipeline

#building categorical pipeline
from sklearn.preprocessing import OneHotEncoder

categorical_pipeline = Pipeline(
    steps=[
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore"))
    ]
)

categorical_pipeline

#combined pipeline
from sklearn.compose import ColumnTransformer

preprocessor = ColumnTransformer(
    transformers=[
        ("num", numeric_pipeline, numerical_features),
        ("cat", categorical_pipeline, categorical_features)
    ]
)

preprocessor

#preprocessing training data
X_train_processed = preprocessor.fit_transform(X_train)

print("Training data processed successfully!")

print(X_train_processed.shape)

# Number of output features after preprocessing
feature_names = preprocessor.get_feature_names_out()

print(f"Total Features After Preprocessing: {len(feature_names)}")

#preprocessing test data

X_test_processed = preprocessor.transform(X_test)

print("Testing data processed successfully!")

print(X_test_processed.shape)

#saving processed feature named
feature_names = preprocessor.get_feature_names_out()

feature_df = pd.DataFrame({
    "Feature_Name": feature_names
})

feature_df.to_csv(
    f"{RESULT_PATH}/processed_feature_names.csv",
    index=False
)

print(f"Total Processed Features : {len(feature_names)}")
print("Feature names saved successfully.")

#converting arrays of xtrain to dataframes

X_train_processed_df = pd.DataFrame(
    X_train_processed.toarray(),
    columns=feature_names
)

X_test_processed_df = pd.DataFrame(
    X_test_processed.toarray(),
    columns=feature_names
)

print(X_train_processed_df.shape)
print(X_test_processed_df.shape)

#saving preprocessor pipeline
joblib.dump(
    preprocessor,
    f"{MODEL_PATH}/preprocessor.pkl"
)

print("Preprocessing pipeline saved successfully!")

# verifyig saved pipeline

loaded_preprocessor = joblib.load(
    f"{MODEL_PATH}/preprocessor.pkl"
)

print(type(loaded_preprocessor))