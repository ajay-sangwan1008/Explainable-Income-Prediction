import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import joblib

from sklearn.metrics import (
    roc_curve,
    auc
)

results_df = pd.read_csv(
    f"{RESULT_PATH}/model_comparison.csv"
)

results_df

#sorting by roc auc curve
results_sorted = results_df.sort_values(
    by="ROC-AUC",
    ascending=False
).reset_index(drop=True)

results_sorted

#sorting by f1 score
results_f1 = results_df.sort_values(
    by="F1 Score",
    ascending=False
).reset_index(drop=True)

results_f1

#model comparison
metrics = [
    "Accuracy",
    "Precision",
    "Recall",
    "F1 Score",
    "ROC-AUC"
]

results_plot = results_df.set_index("Model")[metrics]

ax = results_plot.plot(
    kind="bar",
    figsize=(12, 6)
)

plt.title("Performance Comparison of Machine Learning Models")
plt.ylabel("Score")
plt.xlabel("Model")
plt.xticks(rotation=30)
plt.ylim(0, 1)

plt.legend(
    title="Metric",
    bbox_to_anchor=(1.02, 1),
    loc="upper left"
)

plt.tight_layout()

plt.savefig(
    f"{FIGURE_PATH}/model_performance_comparison.png",
    dpi=300,
    bbox_inches="tight"
)

plt.show()

xgboost_pipeline = joblib.load(
    f"{MODEL_PATH}/xgboost_pipeline.pkl"
)

print("XGBoost pipeline loaded successfully!")
print(type(xgboost_pipeline))

X_test = pd.read_csv(
    f"{PROCESSED_DATA_PATH}/X_test.csv"
)

y_test = pd.read_csv(
    f"{PROCESSED_DATA_PATH}/y_test.csv"
).squeeze()

print("X_test:", X_test.shape)
print("y_test:", y_test.shape)

y_pred_xgb = xgboost_pipeline.predict(X_test)

y_prob_xgb = xgboost_pipeline.predict_proba(X_test)[:, 1]

print("Predictions generated successfully!")

#predictions
print("First 20 predicted classes:")
print(y_pred_xgb[:20])

print("\nFirst 20 predicted probabilities:")
print(y_prob_xgb[:20])

#converting predictions to labels

predicted_income = pd.Series(
    y_pred_xgb
).map({
    0: "<=50K",
    1: ">50K"
})

print(predicted_income.head(20))

#predictions summary

prediction_summary = pd.DataFrame({
    "Actual Income": y_test.values,
    "Predicted Income": predicted_income.values,
    "Probability >50K": y_prob_xgb
})

prediction_summary.head(20)

print("Predicted class distribution:")
print(predicted_income.value_counts())

print("\nActual class distribution:")
print(y_test.value_counts())

